#!/usr/bin/env bash
#
# IASolges.v2 - Constructor del paquete binario para Arch Linux (.pkg.tar.zst)
#
# Genera un paquete instalable con:   sudo pacman -U iasolges-v2-<version>-x86_64.pkg.tar.zst
# Equivalente a lo que produce makepkg, pero sin depender de las herramientas de Arch.
#
set -euo pipefail

RAIZ="$(cd "$(dirname "$0")/.." && pwd)"
cd "$RAIZ"

VERSION="$(node -p "require('./package.json').version")"
APP_DIR="$RAIZ/dist-pkg/linux-unpacked"
STAGE="$RAIZ/dist-pkg/arch-stage"
OUT="$RAIZ/dist-pkg/iasolges-v2-${VERSION}-x86_64.pkg.tar.zst"

if [ ! -d "$APP_DIR" ]; then
  echo "✖ No existe dist-pkg/linux-unpacked. Ejecuta antes: npx electron-builder --linux dir --x64"
  exit 1
fi

echo "› Limpiando escenario..."
rm -rf "$STAGE"
mkdir -p "$STAGE"

echo "› Copiando la aplicacion a opt/..."
install -d "$STAGE/opt/IASolges.v2"
cp -a "$APP_DIR/." "$STAGE/opt/IASolges.v2/"

echo "› Lanzador y menu..."
install -d "$STAGE/usr/bin"
ln -sf /opt/IASolges.v2/iasolges-v2 "$STAGE/usr/bin/iasolges-v2"
install -Dm644 "$RAIZ/build/iasolges-v2.desktop" "$STAGE/usr/share/applications/iasolges-v2.desktop"
install -Dm644 "$RAIZ/build/iasolges-v2.appdata.xml" "$STAGE/usr/share/metainfo/iasolges-v2.metainfo.xml"

for tam in 16 24 32 48 64 128 256 512; do
  src="$RAIZ/build/icons/${tam}x${tam}/apps/iasolges-v2.png"
  [ -f "$src" ] && install -Dm644 "$src" "$STAGE/usr/share/icons/hicolor/${tam}x${tam}/apps/iasolges-v2.png"
done

install -Dm644 "$RAIZ/LICENSE" "$STAGE/usr/share/licenses/iasolges-v2/LICENSE"
install -Dm644 "$RAIZ/README.md" "$STAGE/usr/share/doc/iasolges-v2/README.md"

# El sandbox de Chromium necesita el bit setuid para no pasar --no-sandbox
chmod 4755 "$STAGE/opt/IASolges.v2/chrome-sandbox" 2>/dev/null || true

# Credenciales del titular incluidas en el paquete (no se versionan en el repo)
if [ -f "$RAIZ/resources/credentials.json" ]; then
  install -Dm644 "$RAIZ/resources/credentials.json" "$STAGE/opt/IASolges.v2/resources/credentials.json"
fi

# ---------------------------------------------------------------------------
# .PKGINFO con los nombres de paquete propios de Arch
# ---------------------------------------------------------------------------
SIZE_KB="$(du -sk "$STAGE/opt" | cut -f1)"
BUILD_DATE="$(date -u +%s)"
cat > "$STAGE/.PKGINFO" <<EOF
# Generated by IASolges.v2 packaging
pkgname = iasolges-v2
pkgbase = iasolges-v2
pkgver = ${VERSION}
pkgdesc = Agente inteligente para localizar clientes, presupuestar, crear software con IA y auditar legalmente
url = https://github.com/JMBermejias/IASolgesv2
builddate = ${BUILD_DATE}
packager = Jose Manuel Bernabeu Mejias <jose.bernabeu.iasolges@gmail.com>
size = ${SIZE_KB}
arch = x86_64
license = MIT
depend = alsa-lib
depend = at-spi2-core
depend = atk
depend = cairo
depend = cups-libs
depend = expat
depend = gdk-pixbuf2
depend = glib2
depend = gtk3
depend = libcap
depend = libdrm
depend = libnotify
depend = libxcomposite
depend = libxdamage
depend = libxfixes
depend = libxkbcommon
depend = libxrandr
depend = libxrender
depend = libxss
depend = libxtst
depend = mesa-libgbm
depend = nspr
depend = nss
depend = pango
makedepend = zstd
provides = iasolges-v2=${VERSION}
optdepend = git: publicacion de proyectos generados en repositorios
EOF

echo "› Empaquetando (zstd)..."
rm -f "$OUT"
mkdir -p "$(dirname "$OUT")"
( cd "$STAGE" && tar --format=gnu --owner=0 --group=0 --numeric-owner -cf - . | zstd -19 -T0 -q -o "$OUT" )

echo ""
echo "✔ Paquete Arch generado: $OUT"
echo "  Instalar con:  sudo pacman -U $OUT"